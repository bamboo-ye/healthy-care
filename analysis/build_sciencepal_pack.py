#!/usr/bin/env python3
"""Build a deterministic, synthetic-only SciencePal handoff package from source."""
import hashlib
import json
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'prototype' / 'research'
sys.path.insert(0, str(PUBLIC))
from run_analysis import run
from run_experiments import experiment
from run_methods import methods


def encoded(value):
    return json.dumps(value, ensure_ascii=False, indent=2).encode('utf-8')


def main():
    program = json.loads(subprocess.check_output([
        'node', '-e', 'process.stdout.write(JSON.stringify(require(process.argv[1])))',
        str(PUBLIC / 'research-program.js')], text=True))
    data = json.loads((ROOT / 'analysis/demo-input.json').read_text(encoding='utf-8'))
    report, _ = run(data)
    results = experiment(data)
    method_results = methods(data)
    task = '''# SciencePal核心执行任务：院外轻症数据质量与自主用药情境

这是固定48人、7天窗口的合成方法验证包。它不是临床数据，也不证明产品疗效。
SciencePal官方说明支持文献检索与代码执行：https://sciencepal.ai/help

## 在SciencePal中实际完成

1. 阅读research-program.json中的研究问题与原始来源；核实来源支持的结论及场景局限，特别区分临床病历、院外自述和客观检测标签。
2. 实际执行Python脚本，不仅解释代码。三条命令如下：

python3 run_analysis.py health-research-input.json --out actual-output
python3 run_experiments.py health-research-input.json --out actual-experiments
python3 run_methods.py health-research-input.json --out actual-methods

3. 对照reference/中的本地参考结果，核对输入规范哈希、各项分子分母和三种条件；保留真实stdout、stderr、命令与产物。不要把reference复制为平台执行证据。
4. 解释3天与7天窗口、总体与主题子集的差异；它们是观察窗口敏感性，不是AI消融试验，也不证明因果。
   对轨迹检查首末可用评分、缺失及起始日，不把归档或评分降低改写为痊愈。
   对基率情境核对数学公式；0.1%/1%/5%基率及80%敏感度、95%特异度全部是假设，不是论文或产品性能。
5. 分开报告观察事实、候选线索、方法限制与拟开展的验证。不要编造受试者研究、模型得分、临床准确率或伦理审批。
6. 如需记录平台来源，再使用真实可访问的运行链接执行：

python3 run_analysis.py health-research-input.json --platform SciencePal --run-url 'https://sciencepal.ai/实际运行链接' --out actual-output

来源参数是声明，评审仍需核实SciencePal会话、执行过程与原始文件。若暂时拿不到真实链接，保留local-python标识并如实说明，不能伪造。

## 应交回科研端与比赛材料

- actual-output/report.json：可在默认队列的科研端导入，哈希与全部统计应一致。
- actual-output/*.csv与actual-experiments/experiments.json、experiments.csv。
- actual-methods/methods.json：描述性轨迹与纯假设基率结果，不能导入为临床或主分析报告。
- SciencePal真实项目/会话链接、执行日志与截图、来源核验记录。
- 不超过5页的项目说明、3—5分钟演示、原创性与模型/代码/API/资源声明。

导入一致性校验不能认证平台身份。医生确认不属于本项目必须实现的功能。
'''
    files = {
        'SCIENCEPAL_TASK.md': task.encode('utf-8'),
        'health-research-input.json': encoded(data),
        'run_analysis.py': (PUBLIC / 'run_analysis.py').read_bytes(),
        'run_experiments.py': (PUBLIC / 'run_experiments.py').read_bytes(),
        'run_methods.py': (PUBLIC / 'run_methods.py').read_bytes(),
        'research-program.json': encoded(program),
        'reference/report.local-python.json': encoded(report),
        'reference/experiments.local-python.json': encoded(results),
        'reference/methods.local-python.json': encoded(method_results),
    }
    manifest = {'package_version': 'sciencepal-handoff-2', 'data_origin': 'synthetic_and_hypothetical',
                'scope': 'fixed default 48-subject, seven-day input; independent of current browser filters',
                'platform_execution': 'not_performed', 'canonical_input_sha256': report['input_sha256'],
                'files': [{'path': name, 'sha256_file_bytes': hashlib.sha256(value).hexdigest(), 'bytes': len(value)}
                          for name, value in sorted(files.items())]}
    files['manifest.json'] = encoded(manifest)
    folder = PUBLIC / 'materials'
    folder.mkdir(exist_ok=True)
    with zipfile.ZipFile(folder / 'sciencepal-research-pack.zip', 'w') as archive:
        for name, value in sorted(files.items()):
            item = zipfile.ZipInfo(name, date_time=(2026, 10, 18, 0, 0, 0))
            item.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(item, value)
    (folder / 'research-program.json').write_bytes(encoded(program))
    (folder / 'SCIENCEPAL_TASK.md').write_bytes(files['SCIENCEPAL_TASK.md'])
    (PUBLIC / 'experiment-results.js').write_text('/* Generated by analysis/build_sciencepal_pack.py. */\nwindow.ResearchExperiments = ' + json.dumps(results, ensure_ascii=False) + ';\n', encoding='utf-8')
    print(json.dumps({'status': 'complete', 'sources_added': len(program['sources']), 'protocols': len(program['protocols']),
                      'input_sha256': report['input_sha256'], 'package': str(folder / 'sciencepal-research-pack.zip')}, ensure_ascii=False))


if __name__ == '__main__':
    main()
